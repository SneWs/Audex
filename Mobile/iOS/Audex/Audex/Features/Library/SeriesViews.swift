import SwiftUI

struct SeriesListView: View {
    @Environment(LibraryStore.self) private var library

    var body: some View {
        NavigationStack {
            Group {
                if library.isLoadingPlaylists && library.playlists.isEmpty {
                    ProgressView("Loading series…")
                        .frame(maxWidth: .infinity, maxHeight: .infinity)
                } else if let error = library.playlistsError, library.playlists.isEmpty {
                    ContentUnavailableView {
                        Label("Couldn't Load Series", systemImage: "exclamationmark.triangle")
                    } description: {
                        Text(error)
                    } actions: {
                        Button("Retry") {
                            Task { await library.loadPlaylists() }
                        }
                        .buttonStyle(.borderedProminent)
                    }
                } else if library.playlists.isEmpty {
                    ContentUnavailableView(
                        "No series yet",
                        systemImage: "music.note.list",
                        description: Text("Series created or auto-matched on your Audex server will appear here.")
                    )
                } else {
                    ScrollView {
                        LazyVStack(spacing: 12) {
                            ForEach(library.playlists) { playlist in
                                NavigationLink(value: playlist) {
                                    SeriesCard(playlist: playlist)
                                }
                                .buttonStyle(.plain)
                            }
                        }
                        .padding(.horizontal, 16)
                        .padding(.top, 8)
                        .padding(.bottom, 24)
                    }
                }
            }
            .navigationTitle("Series")
            .refreshable {
                await library.loadPlaylists()
            }
            .task {
                if library.playlists.isEmpty {
                    await library.loadPlaylists()
                }
            }
            .navigationDestination(for: Playlist.self) { playlist in
                SeriesDetailView(playlistID: playlist.id, initialPlaylist: playlist)
            }
            .navigationDestination(for: Book.self) { book in
                BookDetailView(bookID: book.id, initialBook: book)
            }
        }
    }
}

struct SeriesCard: View {
    let playlist: Playlist

    var body: some View {
        HStack(spacing: 14) {
            ZStack {
                RoundedRectangle(cornerRadius: 12, style: .continuous)
                    .fill(AudexColor.coral.opacity(0.14))
                    .frame(width: 48, height: 48)
                Image(systemName: "music.note.list")
                    .font(.title3.weight(.semibold))
                    .foregroundStyle(AudexColor.coral)
            }

            VStack(alignment: .leading, spacing: 4) {
                Text(playlist.name)
                    .font(.headline)
                    .foregroundStyle(.primary)
                    .lineLimit(2)
                    .multilineTextAlignment(.leading)

                Text(subtitleText)
                    .font(.subheadline)
                    .foregroundStyle(.secondary)
                    .lineLimit(1)
            }

            Spacer(minLength: 8)

            Image(systemName: "chevron.right")
                .font(.footnote.weight(.semibold))
                .foregroundStyle(.tertiary)
        }
        .padding(16)
        .background(.regularMaterial, in: RoundedRectangle(cornerRadius: 16, style: .continuous))
        .overlay(
            RoundedRectangle(cornerRadius: 16, style: .continuous)
                .strokeBorder(Color.primary.opacity(0.07), lineWidth: 1)
        )
    }

    private var subtitleText: String {
        let count = playlist.books.count
        var result = "\(count) \(count == 1 ? "book" : "books")"
        if playlist.isAutoGenerated {
            result += " · Auto-matched"
        } else if let ownerEmail = playlist.ownerEmail?.trimmingCharacters(in: .whitespacesAndNewlines),
                  !ownerEmail.isEmpty {
            result += " · \(ownerEmail)"
        }
        return result
    }
}

struct SeriesDetailView: View {
    let playlistID: Int
    var initialPlaylist: Playlist? = nil

    @Environment(AppSession.self) private var session
    @Environment(LibraryStore.self) private var library

    @State private var playlist: Playlist?
    @State private var isLoading = false
    @State private var errorMessage: String?
    @State private var hasLoaded = false

    var body: some View {
        Group {
            if isLoading && (playlist?.books.isEmpty ?? true) {
                ProgressView("Loading series…")
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else if let errorMessage, playlist == nil {
                ContentUnavailableView {
                    Label("Couldn't Load Series", systemImage: "exclamationmark.triangle")
                } description: {
                    Text(errorMessage)
                } actions: {
                    Button("Retry") {
                        Task { await loadSeries(force: true) }
                    }
                    .buttonStyle(.borderedProminent)
                }
            } else if let books = playlist?.books, !books.isEmpty {
                ScrollView {
                    BookGrid(
                        books: books,
                        onFavoriteToggle: { book in
                            await toggleFavorite(book)
                        },
                        onComplete: { book in
                            await completeBook(book)
                        }
                    )
                    .padding(.horizontal, 16)
                    .padding(.top, 8)
                    .padding(.bottom, 24)
                }
            } else {
                ContentUnavailableView(
                    "No books in this series",
                    systemImage: "books.vertical",
                    description: Text("Books added to this series will appear here.")
                )
            }
        }
        .navigationTitle(playlist?.name ?? initialPlaylist?.name ?? "Series")
        .navigationBarTitleDisplayMode(.inline)
        .refreshable {
            await loadSeries(force: true)
        }
        .task {
            if !hasLoaded {
                if playlist == nil, let initialPlaylist {
                    playlist = initialPlaylist
                }
                await loadSeries(force: true)
                hasLoaded = true
            } else {
                syncWithLibrary()
            }
        }
    }

    private func loadSeries(force: Bool) async {
        if !force, hasLoaded { return }
        isLoading = true
        errorMessage = nil
        do {
            let loaded = try await session.api.playlist(id: playlistID)
            playlist = loaded
            if let index = library.playlists.firstIndex(where: { $0.id == playlistID }) {
                library.playlists[index] = loaded
            }
        } catch {
            errorMessage = error.localizedDescription
        }
        isLoading = false
    }

    private func syncWithLibrary() {
        guard var current = playlist else { return }
        for idx in current.books.indices {
            let bookID = current.books[idx].id
            if let libBook = library.books.first(where: { $0.id == bookID }) {
                current.books[idx].isFavorite = libBook.isFavorite
                current.books[idx].isCompleted = libBook.isCompleted
                current.books[idx].progressSec = libBook.progressSec
            }
        }
        playlist = current
    }

    private func toggleFavorite(_ book: Book) async {
        let next = !book.isFavorite
        if var current = playlist, let idx = current.books.firstIndex(where: { $0.id == book.id }) {
            current.books[idx].isFavorite = next
            playlist = current
        }
        library.applyFavorite(bookID: book.id, isFavorite: next)
        do {
            try await session.api.setFavorite(bookID: book.id, isFavorite: next)
        } catch {
            if var current = playlist, let idx = current.books.firstIndex(where: { $0.id == book.id }) {
                current.books[idx].isFavorite = !next
                playlist = current
            }
            library.applyFavorite(bookID: book.id, isFavorite: !next)
        }
    }

    private func completeBook(_ book: Book) async {
        if var current = playlist, let idx = current.books.firstIndex(where: { $0.id == book.id }) {
            current.books[idx].isCompleted = true
            current.books[idx].progressSec = current.books[idx].durationSec
            playlist = current
        }
        await library.completeBook(book.id)
    }
}
